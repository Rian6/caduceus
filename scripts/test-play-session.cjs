const assert=require('node:assert/strict');
const {PlaySession,ConsoleHeartbeat}=require('../dist-electron/play-session');
const game={title:'Game',filePath:'D:\\PS2\\DVD\\game.iso'};
const telemetry={title:'Game',filePath:''};
const session=new PlaySession();
assert.equal(session.resolve(game,null),game,'standard OPL works without RA');
session.console(true);
assert.equal(session.resolve(game,telemetry).title,telemetry.title);
session.console(false);
assert.equal(session.resolve(game,null),null,'stale SMB handle cannot override console disconnect');
assert.equal(session.resolve(null,null),null);
assert.equal(session.resolve(game,null),null,'stale handle remains blocked after a missing sample');
session.console(true);
assert.equal(session.resolve(game,telemetry).title,telemetry.title,'console reconnect restores current game');
session.console(false);
const next={title:'Next',filePath:'D:\\PS2\\DVD\\next.iso'};
assert.equal(session.resolve(next,null),next,'new non-RA game is not blocked');
assert.equal(new PlaySession().resolve(null,telemetry),telemetry,'telemetry recovers an ongoing game after app restart');
const heartbeat=new ConsoleHeartbeat();
assert(heartbeat.update(true,10,1000));
assert(heartbeat.update(true,10,15000));
assert(!heartbeat.update(true,10,16000),'repeated cached connected state expires');
assert(heartbeat.update(true,11,17000),'new console packets restore connection');
assert(!heartbeat.update(false,11,18000));
assert(heartbeat.update(true,0,19000),'counter reset after engine restart is accepted');
console.log('PASS: stale SMB rejection, telemetry expiry, reconnect, new game and restart recovery.');

const merged=new PlaySession().resolve({...game,id:7,gameId:'SLUS_209.46',icon:'https://example.com/gta.jpg'}, {...telemetry,title:'Grand Theft Auto: San Andreas',icon:null});
assert.equal(merged.icon,'https://example.com/gta.jpg','RA title differences must not discard ISO cover');
assert.equal(merged.id,7);assert.equal(merged.filePath,game.filePath);
assert.equal(merged.title,'Grand Theft Auto: San Andreas');
const mismatch=new PlaySession().resolve({...game,gameId:'A',icon:'https://example.com/old.jpg'}, {...telemetry,gameId:'B',icon:null});
assert.equal(mismatch.icon,null,'known different games must not share covers');
